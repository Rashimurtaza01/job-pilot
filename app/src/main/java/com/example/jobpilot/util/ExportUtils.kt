package com.example.jobpilot.util

import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import com.example.jobpilot.export.GeneratedExportFile

object ExportUtils {
    fun shareFile(context: Context, export: GeneratedExportFile) {
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            export.file
        )

        val intent = Intent(Intent.ACTION_SEND).apply {
            type = export.mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, "JobPilot Intelligence Dossier (${export.format})")
            putExtra(Intent.EXTRA_TEXT, "Attached is the research dossier generated by JobPilot Intelligence.")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }

        val chooser = Intent.createChooser(intent, "Share Dossier via...")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        context.startActivity(chooser)
    }

    fun openUrl(context: Context, url: String) {
        if (url.isBlank()) return
        try {
            val intent = Intent(Intent.ACTION_VIEW, android.net.Uri.parse(url)).apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(intent)
        } catch (_: Exception) {}
    }
}
